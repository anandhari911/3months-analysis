import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

leads_file=pd.read_csv('3months.csv')
revenue=pd.read_csv('/course_per_revenue_with_profit_loss.csv')
student=pd.read_csv('/student_converted_records_gmail.csv')
trainer=pd.read_csv('/trainer_records (1).csv')

leads_file["day"]=range(len(leads_file))

revenue["day"]=range(len(revenue))

future_days=pd.DataFrame({"day":range(len(leads_file),len(leads_file)+31)})

from sklearn.ensemble import RandomForestRegressor
for col in ["Total Leads","Total Interested","Total Converted"]:
  model=RandomForestRegressor(n_estimators=100,random_state=0)
  model.fit(leads_file[["day"]],leads_file[[col]])
  predictions=model.predict(future_days).sum()
  print(f"{col}:{round(predictions)}")

for col in ["total_revenue","total_cost","profit_or_loss"]:
  model=RandomForestRegressor(n_estimators=100,random_state=0)
  model.fit(revenue[["day"]],revenue[[col]])
  predictions=model.predict(future_days).sum()
  print(f"{col}:{round(predictions)}")